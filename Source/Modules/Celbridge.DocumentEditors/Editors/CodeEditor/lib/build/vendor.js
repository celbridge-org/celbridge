// vendor.js — Extract the Deno namespace declarations into lib/deno.d.ts
// Run from the build/ directory with Deno installed: npm run vendor
//
// `deno types` prints every library Deno type checks against, concatenated. The editor keeps only the two
// that declare the Deno namespace (deno.ns and the deno.net it references). Monaco's own default library
// already supplies the DOM and web APIs, which matches a deno.json whose lib is ["dom", "deno.ns"].

import { execFileSync } from 'child_process';
import { writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outFile = resolve(__dirname, '..', 'deno.d.ts');

const libraryHeader = /^(?=\/\/ Copyright \d{4}-\d{4} the Deno authors)/m;

function run() {
    const version = execFileSync('deno', ['--version'], { encoding: 'utf8' }).split(' (')[0];
    const allTypes = execFileSync('deno', ['types'], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });

    // deno.ns and deno.net declare the namespace. The unstable library also extends it, but references deno.ns.
    const libraries = allTypes.split(libraryHeader).filter((library) =>
        /^declare namespace Deno \{/m.test(library) && !/<reference lib="deno\.ns"/.test(library));

    if (libraries.length !== 2) {
        throw new Error(`Expected the deno.ns and deno.net libraries, found ${libraries.length}`);
    }

    // A no-default-lib directive in any file drops Monaco's default library from the whole program, and the
    // deno.* libraries the others reference do not exist in Monaco.
    const body = libraries.join('\n')
        .replace(/^\/\/\/ <reference no-default-lib="true" \/>\n/gm, '')
        .replace(/^\/\/\/ <reference lib="deno\.[^"]*" \/>\n/gm, '');

    const header = `// The Deno namespace declarations from \`deno types\` (${version}), for the code editor's TypeScript\n` +
        '// checker. Generated by lib/build/vendor.js. Do not edit.\n\n';

    writeFileSync(outFile, header + body);
    console.log(`Done — deno.d.ts written to lib/ (${version})`);
}

run();
